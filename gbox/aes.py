def _xtime(b):
    b <<= 1
    return (b ^ 0x1b) & 0xff if b & 0x100 else b


def _expand_key(key):
    """44 words for AES-128, returned as 11 round keys of 16 bytes."""
    words = [list(key[i:i + 4]) for i in range(0, 16, 4)]
    rcon = 1
    for i in range(4, 44):
        w = list(words[i - 1])
        if i % 4 == 0:
            w = w[1:] + w[:1]
            w = [_SBOX[b] for b in w]
            w[0] ^= rcon
            rcon = _xtime(rcon)
        words.append([a ^ b for a, b in zip(words[i - 4], w)])
    return [sum(words[r * 4:(r + 1) * 4], []) for r in range(11)]


def _add_round_key(state, rk):
    return [s ^ k for s, k in zip(state, rk)]


def _sub_bytes(state):
    return [_SBOX[b] for b in state]


def _shift_rows(state):
    # state is column-major: byte index = column * 4 + row
    out = [0] * 16
    for c in range(4):
        for r in range(4):
            out[c * 4 + r] = state[((c + r) % 4) * 4 + r]
    return out


def _mix_columns(state):
    out = []
    for c in range(4):
        a0, a1, a2, a3 = state[c * 4:c * 4 + 4]
        out += [
            _xtime(a0) ^ (_xtime(a1) ^ a1) ^ a2 ^ a3,
            a0 ^ _xtime(a1) ^ (_xtime(a2) ^ a2) ^ a3,
            a0 ^ a1 ^ _xtime(a2) ^ (_xtime(a3) ^ a3),
            (_xtime(a0) ^ a0) ^ a1 ^ a2 ^ _xtime(a3),
        ]
    return out


def encrypt_block(block, key):
    """Encrypt one 16-byte block with a 16-byte key (AES-128, no mode)."""
    if len(block) != 16:
        raise ValueError("block must be 16 bytes")
    if len(key) != 16:
        raise ValueError("key must be 16 bytes")
    round_keys = _expand_key(key)
    state = _add_round_key(list(block), round_keys[0])
    for rnd in range(1, 10):
        state = _add_round_key(_mix_columns(_shift_rows(_sub_bytes(state))), round_keys[rnd])
    state = _add_round_key(_shift_rows(_sub_bytes(state)), round_keys[10])
    return bytes(state)


def encrypt_cbc_zero(data, key):
    """AES-CBC with a zero IV and zero padding, as the firmware's web UI does it.

    Zero padding, not PKCS#7: a message that is already a multiple of 16
    bytes gets no extra block. An empty message becomes one all-zero block.
    """
    if not data:
        data = b"\0" * 16
    data = data + b"\0" * (-len(data) % 16)
    prev = b"\0" * 16
    out = []
    for i in range(0, len(data), 16):
        prev = encrypt_block(bytes(a ^ b for a, b in zip(data[i:i + 16], prev)), key)
        out.append(prev)
    return b"".join(out)


def encrypt_password(password):
    """The hex string the login endpoint expects in its `password` query parameter."""
    return encrypt_cbc_zero(password.encode("utf-8"), FIRMWARE_KEY).hex()
